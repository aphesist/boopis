/* The store's host commands (docs/PROTOCOL.md section 1a) as a small interface, so the live provider never touches Tauri and
   tests inject a fake. The host validates every input again; nothing here returns a secret (a key goes in `install`'s request to
   the keychain and no further). The command names and argument names are the contract's: Tauri turns a Rust `stage_id` into
   `stageId` on this side, and the structs (`StoreFilter`, `InstallRequest`, ...) keep the schema's snake_case. Written against the
   contract: `bindings.ts` is generated by the host's workstream and takes over from `invoke` when it has these commands. */
import { invoke as tauriInvoke } from '@tauri-apps/api/core';
import type {
  InstallReceipt, InstallPlan, InstallRequest, StageResult, StoreBrowse, StoreDetail, StoreFilter, StoreScope, StoreSource, UninstallResult, UpdateDiff
} from '../data/types';
import { asHostError } from './bridge';

export type Invoke = <T>(command: string, args?: Record<string, unknown>) => Promise<T>;

export interface StoreBridge {
  catalogList(filter?: StoreFilter, cursor?: string | null, limit?: number): Promise<StoreBrowse>;
  search(query: string, filter?: StoreFilter, cursor?: string | null, limit?: number): Promise<StoreBrowse>;
  refresh(source?: string): Promise<StoreSource[]>;
  itemDetail(id: string): Promise<StoreDetail>;
  stage(id: string): Promise<StageResult>;
  plan(stageId: string, scope?: StoreScope): Promise<InstallPlan>;
  install(request: InstallRequest): Promise<InstallReceipt>;
  uninstall(id: string, deleteCredentials: boolean): Promise<UninstallResult>;
  installed(): Promise<InstallReceipt[]>;
  updateCheck(id?: string): Promise<UpdateDiff[]>;
  update(id: string, request: InstallRequest): Promise<InstallReceipt>;
  rollback(id: string): Promise<InstallReceipt>;
  /** an addition to the contract: switch an installed item on or off (takes effect in the next session) */
  setEnabled(id: string, enabled: boolean): Promise<void>;
  sources(): Promise<StoreSource[]>;
  sourceSetEnabled(id: string, enabled: boolean): Promise<void>;
  sourceAdd(input: { url?: string; path?: string; label?: string }): Promise<StoreSource>;
  sourceRemove(id: string): Promise<void>;
}

const orNull = <T>(v: T | undefined): T | null => (v === undefined ? null : v);

export function tauriStoreBridge(invoke: Invoke = tauriInvoke as Invoke): StoreBridge {
  const call = async <T>(command: string, args?: Record<string, unknown>): Promise<T> => {
    try { return await invoke<T>(command, args); } catch (e) { throw asHostError(e); }
  };
  const done = async (command: string, args?: Record<string, unknown>): Promise<void> => { await call<unknown>(command, args); };
  return {
    catalogList: (filter, cursor, limit) => call('store_catalog_list', { filter: orNull(filter), cursor: orNull(cursor), limit: orNull(limit) }),
    search: (query, filter, cursor, limit) => call('store_search', { query, filter: orNull(filter), cursor: orNull(cursor), limit: orNull(limit) }),
    refresh: (source) => call('store_refresh', { source: orNull(source) }),
    itemDetail: (id) => call('store_item_detail', { id, profile: null }),
    stage: (id) => call('store_stage', { id, profile: null }),
    plan: (stageId, scope) => call('store_plan', { stageId, scope: orNull(scope), profile: null }),
    install: (request) => call('store_install', { request, profile: null }),
    uninstall: (id, deleteCredentials) => call('store_uninstall', { id, deleteCredentials, profile: null }),
    installed: () => call('store_installed', { profile: null }),
    updateCheck: (id) => call('store_update_check', { id: orNull(id), profile: null }),
    update: (id, request) => call('store_update', { id, request, profile: null }),
    rollback: (id) => call('store_rollback', { id, profile: null }),
    setEnabled: (id, enabled) => done('store_set_enabled', { id, enabled, profile: null }),
    sources: () => call('store_sources', {}),
    sourceSetEnabled: (id, enabled) => done('store_source_set_enabled', { id, enabled }),
    sourceAdd: (input) => call('store_source_add', { url: orNull(input.url), path: orNull(input.path), label: orNull(input.label) }),
    sourceRemove: (id) => done('store_source_remove', { id })
  };
}
