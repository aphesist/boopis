def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-preview", action="store_true")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    sc = os.environ.get("FILM_SC", SC_DEFAULT)
    out = a.out or os.path.join(sc, "sound")
    os.makedirs(out, exist_ok=True)
    results = [build_cut(c, out) for c in ("film", "cut15", "bumper")]
    prev, aac = None, None
    if not a.no_preview:
        beats = os.path.join(sc, "script", "beats.json")
        if not os.path.exists(beats):
            beats = os.path.join(os.path.dirname(HERE), "script", "beats.json")
        prev = preview.make(sc, out, results[0]["rows"], beats)
        dec = read_audio(prev["out"])
        aac = {"lags": audit.aac_offset(read_audio(results[0]["paths"]["master"]), dec)}
        print(f"[sound] preview: {prev['out']} (on {prev['picture']}), {prev['cues']}; AAC offset {aac['lags']} samples",
              flush=True)
    with open(os.path.join(out, "sync-audit.md"), "w") as fh:
        fh.write(audit_md(results, aac))
    with open(os.path.join(out, "notes.md"), "w") as fh:
        fh.write(notes_md(results, prev))
    with open(os.path.join(out, "report.json"), "w") as fh:
        json.dump({r["cut"]: {"stats": r["stats"], "paths": r["paths"],
                              "hits": sum(1 for q in r["rows"] if q["hit"]),
                              "in_sync": sum(1 for q in r["rows"] if q["hit"] and q["ok"])} for r in results}
                  | {"preview": prev, "aac": aac}, fh, indent=1, default=float)
    print(f"[sound] done: {out}")


if __name__ == "__main__":
    main()
